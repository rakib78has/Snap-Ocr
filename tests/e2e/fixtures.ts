import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import {
  test as base,
  chromium,
  type BrowserContext,
  type Page,
  type Worker,
} from '@playwright/test';

/**
 * Playwright fixtures for testing the loaded extension.
 *
 * An extension needs `chromium.launchPersistentContext` with --load-extension,
 * and MV3 service workers only start in a headed context or the new headless
 * mode. The extension loaded is dist-e2e/ (see scripts/prepare-e2e.mjs).
 */

const EXTENSION_PATH = resolve(import.meta.dirname, '../../dist-e2e');

/** Origin of the stand-in web page the overlay is injected into. */
export const TEST_ORIGIN = 'https://snap-ocr.test';

export interface ExtensionFixtures {
  context: BrowserContext;
  /** The extension's generated id, needed to build chrome-extension:// URLs. */
  extensionId: string;
  /** The MV3 background service worker. */
  serviceWorker: Worker;
}

export const test = base.extend<ExtensionFixtures>({
  // `headless` is Playwright's own option fixture, so `--headed` still works.
  context: async ({ headless }, use) => {
    const userDataDir = await mkdtemp(join(tmpdir(), 'snap-ocr-profile-'));
    const context = await chromium.launchPersistentContext(userDataDir, {
      channel: 'chromium',
      headless,
      viewport: { width: 1000, height: 700 },
      args: [`--disable-extensions-except=${EXTENSION_PATH}`, `--load-extension=${EXTENSION_PATH}`],
    });

    await use(context);
    await context.close();
    await rm(userDataDir, { recursive: true, force: true });
  },

  serviceWorker: async ({ context }, use) => {
    const existing = context.serviceWorkers();
    const worker = existing[0] ?? (await context.waitForEvent('serviceworker'));
    await use(worker);
  },

  extensionId: async ({ serviceWorker }, use) => {
    await use(new URL(serviceWorker.url()).host);
  },
});

export const expect = test.expect;

export function extensionUrl(extensionId: string, path: string): string {
  return `chrome-extension://${extensionId}/${path}`;
}

/**
 * Renders text onto a white canvas and returns it as a PNG data URL — a
 * deterministic OCR input generated by the same Chromium under test.
 */
export async function renderTextImage(page: Page, lines: string[]): Promise<string> {
  return page.evaluate((textLines) => {
    const canvas = document.createElement('canvas');
    canvas.width = 900;
    canvas.height = 60 + textLines.length * 60;
    const ctx = canvas.getContext('2d')!;
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    ctx.fillStyle = '#000000';
    ctx.font = '36px Arial, sans-serif';
    textLines.forEach((line, i) => ctx.fillText(line, 30, 70 + i * 60));
    return canvas.toDataURL('image/png');
  }, lines);
}

/**
 * Hands an image to the extension exactly as the service worker does after a
 * capture, and returns the result page path that will show it.
 */
export async function seedCapture(
  worker: Worker,
  dataUrl: string,
  captureId = 'e2e-capture'
): Promise<string> {
  await worker.evaluate(([key, image]) => chrome.storage.session.set({ [key]: image }), [
    `snapocr_pending_image:${captureId}`,
    dataUrl,
  ] as const);
  return `result/result.html?capture=${captureId}`;
}

/** Serves `bodyHtml` at TEST_ORIGIN as an ordinary web page and opens it. */
export async function openPage(context: BrowserContext, bodyHtml: string): Promise<Page> {
  await context.route(`${TEST_ORIGIN}/**`, (route) =>
    route.fulfill({
      contentType: 'text/html',
      body: `<!doctype html><html><body style="margin:0;background:#fff">${bodyHtml}</body></html>`,
    })
  );
  const page = await context.newPage();
  await page.goto(`${TEST_ORIGIN}/`);
  return page;
}

/** A page with one line of large text at a known spot, for the overlay to capture. */
export function openTextPage(context: BrowserContext, text: string): Promise<Page> {
  return openPage(
    context,
    `<p id="target" style="position:absolute;left:100px;top:150px;margin:0;
      font:40px Arial,sans-serif;color:#000">${text}</p>`
  );
}

/** Injects the overlay the way the toolbar click does. */
export async function startSelection(worker: Worker): Promise<void> {
  await worker.evaluate(async (origin) => {
    const [tab] = await chrome.tabs.query({ url: `${origin}/*` });
    if (!tab?.id) throw new Error('test page tab not found');
    await chrome.scripting.executeScript({
      target: { tabId: tab.id },
      files: ['selection-overlay.js'],
    });
  }, TEST_ORIGIN);
}
